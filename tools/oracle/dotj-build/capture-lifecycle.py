"""Verify locked inputs and reproduce selected installed lifecycle metadata only.

This runner does not evaluate a project, run a task, build, restore or download.
The checked-in lock is a reviewable trust anchor, never regenerated by this tool.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess

ROOT = Path(r'D:\AI\Implementation\dotj Frameworks')
REPO = Path(__file__).resolve().parents[3]
EVIDENCE = REPO/'planning/stage-2/repos/dotj-build/evidence'
LOCK = EVIDENCE/'compiled-lifecycle-lock-v1.json'


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def verify_inputs(root, repo, records):
    for record in records:
        base = repo if record['base'] == 'repo' else root
        path = (base/record['path']).resolve(strict=True)
        if not path.is_relative_to(base) or sha(path) != record['sha256']:
            raise RuntimeError('Locked input mismatch: '+record['path'])


def verify_mapping(raw, mapping, root):
    types = {t['fullName']: t for t in raw['types']}
    members = {m['id']: m for t in raw['types'] for m in t['methods']}
    for t in raw['types']:
        for prop in t['properties']:
            members[t['fullName']+'::'+prop['name']] = prop
    matched = []
    for anchor in mapping['anchors']:
        source = (root/anchor['source']).read_text(encoding='utf-8-sig').splitlines()
        if source[anchor['line']-1].strip() != anchor['declaration']:
            raise RuntimeError('Source anchor drift: '+str(anchor['line']))
        identity = anchor['compiledIdentity']
        item = types.get(identity) if anchor['kind'] == 'type' else members.get(identity)
        if item is None:
            raise RuntimeError('Missing compiled anchor: '+identity)
        if anchor['kind'] == 'method' and not item['public']:
            raise RuntimeError('Anchor visibility mismatch: '+identity)
        matched.append(identity)
    for row in mapping['overloadSourceNavigation']:
        if row['status'] == 'NO_SOURCE_DECLARATION_MATCH':
            if row['compiledIdentity'] != 'Microsoft.Build.Evaluation.Project::.cctor()':
                raise RuntimeError('Unexpected unmapped declaration: '+row['compiledIdentity'])
            continue
        source = (root/row['source']).read_text(encoding='utf-8-sig').splitlines()
        declaration = '\n'.join(source[row['line']-1:]).lstrip()
        if not declaration.startswith(row['declaration']):
            raise RuntimeError('Overload navigation drift: '+row['compiledIdentity'])
        if row['compiledIdentity'] not in members or members[row['compiledIdentity']]['metadataToken'] != row['metadataToken']:
            raise RuntimeError('Overload metadata navigation drift: '+row['compiledIdentity'])
    for name, expected in mapping['expectedFamilies'].items():
        if sum(m['id'].startswith(name+'(') for m in members.values() if 'id' in m) != expected:
            raise RuntimeError('Overload family drift: '+name)
    return matched


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    output = args.out.resolve()
    if os.name != 'nt' or not output.is_relative_to(ROOT) or output == ROOT or output.exists():
        raise RuntimeError('--out must be a new private directory below the original D: project root')
    output.mkdir(parents=True)
    record = {'schemaVersion': 1, 'status': 'VERIFYING_INPUTS', 'commands': [],
              'lockSha256': sha(LOCK), 'productQualification': False, 'acceptedTasksAdded': 0,
              'machine': {'system': platform.system(), 'release': platform.release(), 'machine': platform.machine(),
                          'pythonVersion': platform.python_version()}}

    def save():
        (output/'verification.json').write_text(json.dumps(record, indent=2)+'\n', encoding='utf-8')

    save()
    try:
        lock = json.loads(LOCK.read_text(encoding='utf-8'))
        verify_inputs(ROOT, REPO, lock['inputs'])
        record['verifiedInputs'] = len(lock['inputs'])
        prior = json.loads((ROOT/'agents/validation-performance/build-frontier-research/sdk-entry-provenance.json').read_text())
        for row in prior['rows']:
            path = Path(row['installedPath']).resolve(strict=True)
            if not path.is_relative_to(ROOT) or sha(path) != row['installedSha256'] or row['installedSha256'] != row['archiveEntrySha256']:
                raise RuntimeError('Installed SDK differs from retained archive-entry evidence: '+str(path))
        record['matchedPriorSdkEntries'] = len(prior['rows'])
        environment = os.environ.copy()
        for key in list(environment):
            if key.startswith(('DOTNET_', 'COMPlus_', 'CORECLR_', 'COR_')) or key in ('PSModulePath', 'PSExecutionPolicyPreference'):
                environment.pop(key)
        for folder in ['tmp', 'home', 'modules']:
            (output/folder).mkdir()
        environment.update(TEMP=str(output/'tmp'), TMP=str(output/'tmp'),
                           USERPROFILE=str(output/'home'), HOME=str(output/'home'),
                           DOTNET_ROOT=str(ROOT/'toolchains/dotnet'),
                           DOTNET_CLI_HOME=str(output/'home'), DOTNET_CLI_TELEMETRY_OPTOUT='1',
                           DOTNET_SKIP_FIRST_TIME_EXPERIENCE='1', DOTNET_MULTILEVEL_LOOKUP='0',
                           DOTNET_PROCESSOR_COUNT='2', DOTNET_GCHeapHardLimit='0x10000000',
                           DOTNET_EnableDiagnostics='0')
        argv = [str(ROOT/'toolchains/dotnet/dotnet.exe'), 'exec', '--runtimeconfig',
                str(ROOT/'toolchains/powershell-oracle.runtimeconfig.json'),
                str(ROOT/'toolchains/powershell-7.6.0-fxdependent/pwsh.dll'),
                '-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
                '-File', str(Path(__file__).with_name('read-lifecycle.ps1')),
                '-ImplementationRoot', str(ROOT)]
        command = {'argv': argv, 'cwd': str(output), 'environmentOverrides': {
            k: environment[k] for k in environment if k.startswith('DOTNET_') or k in ('TEMP', 'TMP', 'USERPROFILE', 'HOME')}}
        record['commands'].append(command)
        record['status'] = 'READING_METADATA'
        save()
        result = subprocess.run(argv, cwd=output, env=environment, capture_output=True, timeout=120)
        command['exitCode'] = result.returncode
        for name, data in [('metadata.json', result.stdout), ('stderr.txt', result.stderr)]:
            (output/name).write_bytes(data)
            command[name] = {'path': str(output/name), 'sha256': sha(output/name), 'bytes': len(data)}
        if result.returncode or result.stderr:
            raise RuntimeError('Metadata reader failed; inspect retained stderr')
        if sha(output/'metadata.json') != lock['expectedMetadataSha256']:
            raise RuntimeError('Compiled metadata differs from locked baseline')
        raw = json.loads(result.stdout)
        mapping = json.loads((EVIDENCE/'compiled-lifecycle-mapping-v1.json').read_text(encoding='utf-8'))
        record['matchedAnchors'] = verify_mapping(raw, mapping, ROOT)
        record['methodCount'] = sum(len(t['methods']) for t in raw['types'])
        record['propertyCount'] = sum(len(t['properties']) for t in raw['types'])
        record['directContractCount'] = len(raw['directContracts'])
        record['hostRuntime'] = raw['hostRuntime']
        if raw['hostRuntime'] != '.NET 10.0.12' or raw['powershellVersion'] != '7.6.0':
            raise RuntimeError('Unexpected host profile')
        # Bind every resolved metadata image to the already checked resolver lock.
        locked = {str((ROOT/i['path']).resolve()): i['sha256'] for i in lock['inputs'] if i['base'] == 'root'}
        record['resolvedAssemblies'] = []
        for assembly in raw['loadedAssemblies']:
            path = Path(assembly['path']).resolve(strict=True)
            if str(path) not in locked or sha(path) != locked[str(path)]:
                raise RuntimeError('Unpinned resolved assembly: '+str(path))
            record['resolvedAssemblies'].append(dict(assembly, sha256=locked[str(path)]))
        verify_inputs(ROOT, REPO, lock['inputs'])
        record['status'] = 'PASS_SELECTED_METADATA_ONLY'
    except Exception as error:
        record.update(status='REFUSED', error=str(error))
        raise
    finally:
        save()
    print(json.dumps({k: record[k] for k in ['status', 'verifiedInputs', 'methodCount', 'propertyCount', 'directContractCount']}))


if __name__ == '__main__':
    main()
